// ---------- Fill the crest and each medallion with its icon (single source: content above) ----------
document.querySelector('.crest-circle').innerHTML = content.crest.icon;
document.querySelectorAll('.medallion-btn').forEach(btn => {
  const entry = content[btn.dataset.key];
  const circle = btn.querySelector('.medallion-circle');
  if (entry && circle) circle.innerHTML = entry.icon;
});

// ---------- Modal wiring ----------
const modal = document.getElementById('info-modal');
const modalTitle = document.getElementById('modal-title');
const modalBody = document.getElementById('modal-body');
const modalIcon = document.getElementById('modal-icon');
const closeBtn = document.getElementById('modal-close');
let lastFocused = null;

function openModal(key){
  const entry = content[key];
  if (!entry) return;
  modalTitle.textContent = entry.title;
  modalIcon.innerHTML = entry.icon;
  modalBody.innerHTML = entry.body.map(p => `<p>${p}</p>`).join('');
  lastFocused = document.activeElement;
  modal.showModal();
  closeBtn.focus();
}

function closeModal(){
  modal.close();
}

document.querySelectorAll('[data-key]').forEach(btn => {
  btn.addEventListener('click', () => openModal(btn.dataset.key));
});

closeBtn.addEventListener('click', closeModal);

// Close when the backdrop (not the card itself) is clicked
modal.addEventListener('click', (event) => {
  if (event.target === modal) closeModal();
});

// Native <dialog> already closes on Escape; keep state tidy afterwards too
modal.addEventListener('close', () => {
  if (lastFocused) lastFocused.focus();
});
